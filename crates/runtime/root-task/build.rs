//! root-task 链接配置：作为 seL4 rootserver，ELF 入口必须是 `_start`
//! （seL4 kernel 以 ELF entry 创建初始线程）。Rust 默认把 `main` 设为
//! 入口，这里用 `-e _start` 强制覆盖（rust-lld）。
//!
//! 同时强制 4 KiB 页对齐（`-z max-page-size=0x1000`）：spawn 计划解析
//! root 模块（bundle 中的 root-task ELF）时要求段 vaddr 页对齐
//! （`seg.vaddr % PAGE_SIZE == 0`，否则 `SpawnError::PlanMismatch`）；
//! rust-lld 默认 64 KiB max-page-size 导致非页对齐（C2/BOOT-007 迭代修复）。
fn main() {
    // 70.6（WP-70.6.5）：MGT1 探针测试数据生成（仅 qemu-test-synth 测试
    // 装配构建且 gate 显式导出 env 时；release 构建无 env → 空数据文件，
    // 探针代码经 cfg(feature) 不编译）。测试 station token/签名对与候选
    // 配置束由 gate（run70-vol6-gate.sh 段0/段1）生成后经 env 注入，
    // 私钥永不出 gate 运行目录。
    let probe_out =
        std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("mgt_probe_data.rs");
    if std::env::var("CARGO_FEATURE_QEMU_TEST_SYNTH").is_ok() {
        let token = std::env::var("ENEROS_MGT_PROBE_TOKEN").unwrap_or_default();
        let sig = std::env::var("ENEROS_MGT_PROBE_SIG").unwrap_or_default();
        let hex_bytes = |h: &str| -> String {
            let b = h.as_bytes();
            let mut parts = Vec::new();
            let mut i = 0;
            while i + 1 < b.len() {
                parts.push(format!("0x{}{}", b[i] as char, b[i + 1] as char));
                i += 2;
            }
            parts.join(", ")
        };
        let mut body = String::from(
            "// @generated by build.rs（gate 注入的探针测试数据）\n",
        );
        body.push_str(&format!(
            "pub const PROBE_TOKEN: &[u8] = &[{}];\n",
            hex_bytes(&token)
        ));
        body.push_str(&format!(
            "pub const PROBE_SIG: &[u8] = &[{}];\n",
            hex_bytes(&sig)
        ));
        if let Ok(bundle_path) = std::env::var("ENEROS_MGT_PROBE_BUNDLE") {
            body.push_str(&format!(
                "pub const PROBE_BUNDLE: &[u8] = include_bytes!({bundle_path:?});\n"
            ));
        } else {
            body.push_str("pub const PROBE_BUNDLE: &[u8] = &[];\n");
        }
        std::fs::write(&probe_out, body).expect("write mgt_probe_data.rs");
        println!("cargo:rerun-if-env-changed=ENEROS_MGT_PROBE_TOKEN");
        println!("cargo:rerun-if-env-changed=ENEROS_MGT_PROBE_SIG");
        println!("cargo:rerun-if-env-changed=ENEROS_MGT_PROBE_BUNDLE");
    } else {
        let _ = std::fs::write(
            &probe_out,
            "pub const PROBE_TOKEN: &[u8] = &[];\npub const PROBE_SIG: &[u8] = &[];\npub const PROBE_BUNDLE: &[u8] = &[];\n",
        );
    }
    // 仅对裸机 target 注入（host 构建用于测试，不需强制入口）。
    if std::env::var("TARGET")
        .map(|t| t == "aarch64-unknown-none")
        .unwrap_or(false)
    {
        println!("cargo:rustc-link-arg=-e");
        println!("cargo:rustc-link-arg=_start");
        println!("cargo:rustc-link-arg=-z");
        println!("cargo:rustc-link-arg=max-page-size=0x1000");
        // separate-code：让代码/数据段分别页对齐（vaddr % 4096 == 0）。
        // 实测仅 max-page-size 不足以对齐段 vaddr（.text 起始偏移仍
        // 非页对齐）；separate-code 强制每个 PT_LOAD 页对齐。
        println!("cargo:rustc-link-arg=-z");
        println!("cargo:rustc-link-arg=separate-code");
        // WP-37.4（rootserver 装载对齐敏感）：强制 .text 起始 0x210000
        // （64K 边界）——QEMU 实测 text 起始 0x208000（0x8000 偏移）时
        // text 尾部页内容异常（EC=0 user exception）；64K 对齐起始布局
        // 正常。确定性锚（非布局碰运气）：37 记录 §16 登记 kernel 侧
        // 根因调查（42/43）。
        println!("cargo:rustc-link-arg=--section-start=.text=0x210000");
    }
}
